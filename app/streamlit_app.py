"""DompetKu e-wallet dashboard: Part B of sql-case-studies.

Reads only app/data/*.parquet (made by `uv run sqlcases snapshot`), so it runs without a
database, e.g. on Streamlit Community Cloud. Every chart shows the SQL that produced it.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

APP = Path(__file__).resolve().parent
DATA = APP / "data"
PART_B = APP.parent / "part-b"

# Reference palette (validated: first three slots pass all-pairs CVD checks in light mode).
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
RED = "#e34948"  # diverging negative pole
INK, INK_2, MUTED = "#0b0b0b", "#52514e", "#898781"
GRID, AXIS, SURFACE = "#e1e0d9", "#c3c2b7", "#fcfcfb"
SEQ = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]

st.set_page_config(page_title="DompetKu e-wallet analytics", page_icon="📊", layout="wide")


@st.cache_data
def load(name: str) -> pd.DataFrame:
    return pd.read_parquet(DATA / f"{name}.parquet")


def sql(rel: str, label: str = "SQL behind this chart") -> None:
    with st.expander(label):
        st.code((PART_B / rel).read_text(encoding="utf-8"), language="sql")


def data_view(df: pd.DataFrame) -> None:
    with st.expander("Show data"):
        st.dataframe(df, hide_index=True, use_container_width=True)


def style(fig: go.Figure, height: int = 360, legend: bool = False) -> go.Figure:
    fig.update_layout(
        height=height,
        margin=dict(l=8, r=8, t=8, b=8),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font=dict(family="system-ui, -apple-system, Segoe UI, sans-serif", color=INK_2, size=13),
        showlegend=legend,
        legend=dict(orientation="h", y=1.08, x=0, font=dict(color=INK_2)),
        hoverlabel=dict(bgcolor="white", font_color=INK, bordercolor=AXIS),
    )
    fig.update_xaxes(gridcolor=GRID, linecolor=AXIS, tickfont=dict(color=MUTED), zeroline=False)
    fig.update_yaxes(gridcolor=GRID, linecolor=AXIS, tickfont=dict(color=MUTED), zeroline=False)
    return fig


def show(fig: go.Figure) -> None:
    st.plotly_chart(fig, use_container_width=True, config={"displayModeBar": False})


